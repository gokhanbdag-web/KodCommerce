import assert from 'node:assert/strict';
import {createHistory, copyWidget, pasteWidget} from '../public/assets/js/page-editor-history.mjs';
const layout=[{columns:[{widgets:[{type:'text',text:'First'}]},{widgets:[]}]}];
const history=createHistory(2);
assert.equal(history.canUndo,false);
history.capture(layout);
layout[0].columns[0].widgets[0].text='Edited';
assert.equal(history.canUndo,true);
const before=history.undo();
assert.equal(before[0].columns[0].widgets[0].text,'First');
assert.equal(history.canUndo,false);
const copied=copyWidget(layout,0,0,0);
assert.equal(pasteWidget(layout,0,1,copied),true);
copied.text='Changed clipboard';
assert.equal(layout[0].columns[1].widgets[0].text,'Edited','paste deep-clones copied widget');
assert.equal(pasteWidget(layout,4,0,copied),false);
assert.equal(pasteWidget(layout,0,1,null),false);
layout[0].columns[1].widgets=Array.from({length:30},()=>({type:'text',text:'x'}));
assert.equal(pasteWidget(layout,0,1,copied),false,'respects 30 widget cap');
history.capture(layout);
history.capture(layout);
history.capture(layout);
assert.ok(history.canUndo);
assert.notEqual(history.undo(),null);
assert.notEqual(history.undo(),null);
assert.equal(history.undo(),null,'bounded undo history');
history.capture(layout);
history.clear();
assert.equal(history.canUndo,false);
console.log('Page editor clipboard and undo tests passed');
